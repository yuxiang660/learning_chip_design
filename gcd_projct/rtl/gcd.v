// ============================================================================
// GCD计算器 - 使用欧几里得算法（减法版本）
// ============================================================================
// 
// EDA概念说明：
// 1. 这是一个同步时序电路，所有状态更新都在时钟边沿发生
// 2. 使用有限状态机(FSM)控制计算流程
// 3. 采用握手协议(Valid-Ready)与外部通信
//
// 算法：重复执行 a = a - b (当a >= b) 或交换a,b，直到b=0
// ============================================================================

module gcd #(
    parameter WIDTH = 16  // 数据位宽，可配置为8/16/32等
)(
    // 时钟和复位
    input  wire             clk,      // 时钟信号，同步所有操作
    input  wire             rst_n,    // 复位信号，低电平有效（异步复位）
    
    // 输入握手接口 (Valid-Ready Protocol)
    // EDA概念：握手协议确保数据传输的可靠性
    input  wire             req_val,      // 输入有效信号（主设备发出）
    output wire             req_rdy,      // 输入就绪信号（从设备发出）
    input  wire [WIDTH-1:0] req_msg_a,    // 输入数据A
    input  wire [WIDTH-1:0] req_msg_b,    // 输入数据B
    
    // 输出握手接口
    output reg              resp_val,     // 输出有效信号
    input  wire             resp_rdy,     // 输出就绪信号
    output reg  [WIDTH-1:0] resp_msg      // 输出结果（GCD值）
);

    // ========================================================================
    // 状态机定义
    // EDA概念：状态编码
    // - 使用localparam定义状态常量
    // - 2位可以表示4个状态，这里用3个
    // ========================================================================
    localparam STATE_IDLE = 2'b00;  // 空闲状态，等待输入
    localparam STATE_CALC = 2'b01;  // 计算状态，执行GCD算法
    localparam STATE_DONE = 2'b10;  // 完成状态，输出结果
    
    // ========================================================================
    // 寄存器声明
    // EDA概念：这些都会被综合成触发器(Flip-Flops)
    // ========================================================================
    reg [1:0]       state, next_state;      // 当前状态和下一状态
    reg [WIDTH-1:0] a_reg, a_next;          // 操作数A的当前值和下一值
    reg [WIDTH-1:0] b_reg, b_next;          // 操作数B的当前值和下一值
    
    // ========================================================================
    // 组合逻辑：输出就绪信号
    // EDA概念：只有在IDLE状态才能接收新的输入
    // ========================================================================
    assign req_rdy = (state == STATE_IDLE);
    
    // ========================================================================
    // 时序逻辑：状态和数据寄存器更新
    // EDA概念：
    // - always @(posedge clk) 表示在时钟上升沿触发
    // - 使用非阻塞赋值 <= （在时序逻辑中使用）
    // - 异步复位：复位不依赖时钟，立即生效
    // ========================================================================
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            // 复位：所有寄存器初始化
            state <= STATE_IDLE;
            a_reg <= {WIDTH{1'b0}};  // 全0
            b_reg <= {WIDTH{1'b0}};
        end else begin
            // 正常工作：更新状态和数据
            state <= next_state;
            a_reg <= a_next;
            b_reg <= b_next;
        end
    end
    
    // ========================================================================
    // 组合逻辑：下一状态和输出逻辑
    // EDA概念：
    // - always @(*) 表示组合逻辑，对所有输入敏感
    // - 使用阻塞赋值 = （在组合逻辑中使用）
    // - 必须对所有信号赋默认值，避免产生锁存器(Latch)
    // ========================================================================
    always @(*) begin
        // 默认值：保持当前状态
        // EDA重要概念：避免Latch
        // 如果组合逻辑中某个信号在某些条件下没有赋值，会推断出锁存器
        // 这通常是不希望的，会导致时序问题
        next_state = state;
        a_next = a_reg;
        b_next = b_reg;
        resp_val = 1'b0;
        resp_msg = {WIDTH{1'b0}};
        
        case (state)
            // ================================================================
            // IDLE状态：等待输入数据
            // ================================================================
            STATE_IDLE: begin
                // 握手成功：req_val和req_rdy都为高
                if (req_val && req_rdy) begin
                    // 加载输入数据到内部寄存器
                    a_next = req_msg_a;
                    b_next = req_msg_b;
                    // 转到计算状态
                    next_state = STATE_CALC;
                end
            end
            
            // ================================================================
            // CALC状态：执行GCD算法
            // EDA概念：这是一个迭代算法的硬件实现
            // - 每个时钟周期执行一次减法或交换
            // - 不是一个周期完成，而是多周期操作
            // ================================================================
            STATE_CALC: begin
                if (b_reg == 0) begin
                    // 终止条件：b为0，a就是GCD结果
                    next_state = STATE_DONE;
                end else begin
                    // 继续迭代
                    if (a_reg >= b_reg) begin
                        // a >= b: 执行 a = a - b
                        a_next = a_reg - b_reg;
                        // b保持不变
                    end else begin
                        // a < b: 交换a和b
                        a_next = b_reg;
                        b_next = a_reg;
                    end
                    // 保持在CALC状态，继续下一次迭代
                    // next_state = STATE_CALC; (已经是默认值)
                end
            end
            
            // ================================================================
            // DONE状态：输出结果
            // ================================================================
            STATE_DONE: begin
                // 设置输出有效信号
                resp_val = 1'b1;
                // 输出结果（a_reg中存储的GCD值）
                resp_msg = a_reg;
                
                // 等待接收方准备好
                if (resp_rdy) begin
                    // 握手完成，返回IDLE状态等待下一个输入
                    next_state = STATE_IDLE;
                end
                // 如果resp_rdy=0，继续保持在DONE状态
            end
            
            // ================================================================
            // 默认情况：异常恢复
            // EDA概念：防御性编程，处理未定义状态
            // ================================================================
            default: begin
                next_state = STATE_IDLE;
            end
        endcase
    end

endmodule

// ============================================================================
// RTL设计要点总结：
// 
// 1. 时序逻辑 vs 组合逻辑的区分
//    - 时序：always @(posedge clk)，使用 <= 
//    - 组合：always @(*)，使用 =
//
// 2. 避免Latch的方法
//    - 在组合逻辑中为所有信号赋默认值
//    - 确保所有分支都对信号赋值
//
// 3. 状态机设计模式
//    - 三段式：状态寄存器 + 下一状态逻辑 + 输出逻辑
//    - 便于综合和时序分析
//
// 4. 握手协议
//    - Valid-Ready机制确保数据传输可靠
//    - 发送方设置valid，接收方设置ready
//    - 双方都为高时传输发生
//
// 5. 参数化设计
//    - 使用parameter使设计可配置
//    - 便于复用和综合优化
// ============================================================================
